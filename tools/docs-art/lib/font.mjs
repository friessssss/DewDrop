// Bold forms for letters whose 1px gaps would close up under faux bold. Drawn as-is, without thickening.
const BOLD = {
  M: ["##...##", "###.###", "#######", "##.#.##", "##...##", "##...##", "##...##"],
  W: ["##...##", "##...##", "##...##", "##.#.##", "##.#.##", "#######", ".##.##."],
  m: [".......", ".......", "###.##.", "#######", "##.#.##", "##.#.##", "##.#.##"],
  w: [".......", ".......", "##...##", "##.#.##", "##.#.##", "#######", ".##.##."],
};

for (const [ch, rows] of [...Object.entries(G), ...Object.entries(BOLD)]) {
  const w = rows[0].length;
  if (rows.some((r) => r.length !== w)) throw new Error(`glyph ${JSON.stringify(ch)} has ragged rows`);
}

export const CAP = 7;      // cap height
export const LINE = 11;    // line advance, including descenders and a gap

export function glyph(ch) {
  return G[ch] ?? G['?'];
}

/** Width in font pixels of a string at scale 1 (no trailing gap). */
function form(ch, bold) {
  return bold && BOLD[ch] ? { rows: BOLD[ch], thicken: false } : { rows: glyph(ch), thicken: bold };
}

export function measure(text, { bold = false, spacing = 1 } = {}) {
  let w = 0;
  for (const ch of text) {
    const { rows, thicken } = form(ch, bold);
    w += rows[0].length + (thicken ? 1 : 0) + spacing;
  }
  return Math.max(0, w - spacing);
}

/** Calls plot(x, y) for every lit font pixel, starting at the top-left of the cap height. */
export function rasterize(text, plot, { bold = false, spacing = 1 } = {}) {
  let cx = 0;
  for (const ch of text) {
    const { rows, thicken } = form(ch, bold);
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] === '#') {
          plot(cx + x, y);
          // Faux bold thickens each stroke to the right, except where that would close a 1px gap (W, M, m, w...).
          if (thicken && row[x + 2] !== '#') plot(cx + x + 1, y);
        }
      }
    });
    cx += rows[0].length + (thicken ? 1 : 0) + spacing;
  }
}

/** Greedy word wrap to a width in font pixels. */
export function wrap(text, maxWidth, opts = {}) {
  const lines = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const next = line ? `${line} ${word}` : word;
      if (measure(next, opts) > maxWidth && line) {
        lines.push(line);
        line = word;
      } else line = next;
    }
    lines.push(line);
  }
  return lines;
}
